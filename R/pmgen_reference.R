#' Specify a Reference Model for Sample Size Calculations
#'
#' Constructs a reference logistic regression model by finding the intercept
#' and coefficient scalar that jointly achieve a target prevalence and
#' c-statistic in the joint predictor distribution. The unit Fisher information
#' matrix is also computed and stored in the returned object.
#'
#' @param joint_data A data frame (one row per individual, columns = predictors)
#'   representing the joint predictor distribution. Alternatively, a named list
#'   of distributional assumptions (see Details). Required.
#' @param predictors Character vector of predictor column names to use from
#'   `joint_data`. If `NULL`, all columns of `joint_data` are used (when
#'   `joint_data` is a data frame).
#' @param coef Named numeric vector of predictor coefficients. Names must
#'   match `predictors`. Meaning depends on `bisection`: when `bisection =
#'   TRUE`, these are *relative weights* (on the log-odds scale, before
#'   scaling) — if `NULL`, all predictors are given equal weight of 1. When
#'   `bisection = FALSE`, these are the *final* coefficients used directly
#'   (no default; must be supplied).
#' @param bisection Logical. If `TRUE` (default), run the two-step bisection
#'   procedure to calibrate `coef`/`intercept` against `prevalence`/
#'   `cstatistic`. If `FALSE`, bypass bisection entirely and use the supplied
#'   `intercept`/`coef` directly as the reference model — useful when a
#'   reference model has already been fully specified elsewhere (e.g. from
#'   the literature) and bisection-based calibration is not wanted.
#' @param bisection_method One of `"independent"` (default) or `"mvn"`.
#'   Only used when `bisection = TRUE` and `joint_data` is a data frame.
#'   `"independent"` calibrates against a synthetic population generated by
#'   fitting independent marginal distributions to `joint_data` (fast, but
#'   discards correlation between predictors). `"mvn"` instead calibrates
#'   against a synthetic population drawn from a multivariate normal
#'   approximation to `joint_data` that preserves its correlation structure
#'   (binary columns are dichotomized after generation); see Details.
#'   `"mvn"` is not supported when `joint_data` is a distributional-
#'   assumptions list (predictors are already independent there by
#'   construction).
#' @param intercept Numeric scalar. Required when `bisection = FALSE`;
#'   ignored when `bisection = TRUE` (the intercept is instead solved for by
#'   the inner bisection).
#' @param prevalence Target outcome prevalence (0, 1). Required when
#'   `bisection = TRUE`. Optional when `bisection = FALSE` — if supplied, the
#'   achieved prevalence is compared to it for informational reporting only.
#' @param cstatistic Target c-statistic (AUC), must be > 0.5. Required when
#'   `bisection = TRUE`. Optional when `bisection = FALSE` — if supplied, the
#'   achieved c-statistic is compared to it for informational reporting only.
#' @param tolerance Convergence tolerance for both bisection procedures.
#'   Default `0.001`. Unused when `bisection = FALSE`.
#' @param n_bisect_pop Integer. Size of the super-population used internally
#'   during bisection. Larger values give more stable estimates but are slower.
#'   Default `1e6`. Unused when `bisection = FALSE`.
#' @param n_synth Integer. When `joint_data` is a distributional-assumptions
#'   list, the number of synthetic individuals to generate. Default `1e6`.
#' @param max_iter Integer. Maximum bisection iterations. Default `100`.
#'   Unused when `bisection = FALSE`.
#' @param seed Integer or NULL. Random seed for reproducibility.
#'
#' @details
#' **Supplying a dataset** (`joint_data` as a data frame): The data frame is
#' used directly as the super-population for bisection and for computing the
#' unit information matrix. This is the recommended approach when synthetic or
#' real pilot data are available.
#'
#' **Supplying distributional assumptions** (`joint_data` as a named list):
#' Each list element specifies the marginal distribution of one predictor:
#' `list(dist = "normal", mean = 50, sd = 10)` or
#' `list(dist = "bernoulli", prob = 0.3)`. Predictors are assumed independent.
#' A synthetic population of `n_synth` rows is generated before bisection.
#'
#' The bisection procedure follows Austin's two-step approach:
#' 1. **Inner bisection (intercept)**: for a fixed scalar `s`, find the
#'    intercept `b0` such that mean(plogis(b0 + s * X %*% coef)) = prevalence.
#' 2. **Outer bisection (scalar)**: find `s` such that the c-statistic of
#'    the resulting model in the super-population equals `cstatistic`.
#'
#' **Bypassing bisection** (`bisection = FALSE`): supply `intercept` and
#' `coef` directly as the final reference model. This is useful when the
#' reference model's coefficients are already known (e.g. published in the
#' literature) and bisecting against a synthetic population derived from
#' `joint_data` is undesirable — for instance, because it would assume
#' predictor independence when `joint_data` is a data frame (see
#' `.fit_marginals()`). The unit information matrix is still computed from
#' `joint_data` as usual.
#'
#' **Correlation-preserving bisection** (`bisection_method = "mvn"`): when
#' `joint_data` is a data frame with correlated predictors, calibrating
#' against a synthetic population that assumes independence (the default
#' `"independent"` method) can distort the calibrated reference model. The
#' `"mvn"` method instead estimates a multivariate normal approximation to
#' `joint_data` (means, SDs, and the full correlation matrix, via `cor()`)
#' and analytically solves for the linear predictor's mean and variance
#' needed to hit the target `prevalence`/`cstatistic` (assuming a normal
#' linear predictor), then rescales `coef` so the resulting predictor
#' combination has that variance. Binary (0/1) columns are generated as
#' normal and then dichotomized to match their empirical proportion; this
#' mildly attenuates their correlation with other predictors relative to the
#' input correlation matrix (no correction is applied for this).
#'
#' Note that bisection without `coef` gives every predictor the same
#' coefficient. If the predictors' true effects differ (in size or sign), this
#' equal-weights model can give noticeably different simulation results (e.g.
#' a different expected calibration slope at small N) from the true model;
#' supply `coef` (relative weights) where they are known.
#'
#' @return A `pmgen_ref_model` object with components: `coef`, `intercept`,
#'   `prevalence_achieved`, `cstat_achieved`, `predictors`, `joint_data`,
#'   `unit_info_matrix`, `inv_unit_info`.
#'
#' @examples
#' # n_bisect_pop and n_synth are reduced from their defaults (1e6) so that
#' # the examples run quickly; use the defaults in practice.
#'
#' # From a supplied dataset (equal relative weights for all predictors)
#' predictors <- setdiff(names(dvt_data), "dvt")
#' ref <- pmgen_reference(
#'   joint_data   = dvt_data,
#'   predictors   = predictors,
#'   prevalence   = 0.21,
#'   cstatistic   = 0.78,
#'   n_bisect_pop = 1e5,
#'   n_synth      = 1e5,
#'   seed         = 42
#' )
#' ref
#'
#' # From distributional assumptions
#' ref_dist <- pmgen_reference(
#'   joint_data = list(
#'     age  = list(dist = "normal",    mean = 0, sd = 1),
#'     bp   = list(dist = "normal",    mean = 0, sd = 1),
#'     hist = list(dist = "bernoulli", prob = 0.3)
#'   ),
#'   prevalence   = 0.10,
#'   cstatistic   = 0.75,
#'   n_bisect_pop = 1e5,
#'   n_synth      = 1e5,
#'   seed         = 42
#' )
#'
#' # Bypassing bisection with a fully pre-specified reference model
#' ref_fixed <- pmgen_reference(
#'   joint_data = dvt_data,
#'   predictors = c("malignancy", "calf_diff", "ab_ddimer"),
#'   bisection  = FALSE,
#'   intercept  = -2.5,
#'   coef       = c(malignancy = 0.5, calf_diff = 0.8, ab_ddimer = 1.5),
#'   n_synth    = 1e5,
#'   seed       = 42
#' )
#' @references
#' Riley RD, Whittle R, Sadatsafavi M, Martin GP, Pate A, Collins GS, Ensor J. A general sample size framework
#' for developing or updating a predictive algorithm: with application to
#' clinical prediction models. *BMC Medical Research Methodology*.
#' 2026;26:121. \doi{10.1186/s12874-026-02856-7}
#' @export
pmgen_reference <- function(joint_data,
                           predictors      = NULL,
                           coef            = NULL,
                           bisection       = TRUE,
                           bisection_method = c("independent", "mvn"),
                           intercept       = NULL,
                           prevalence      = NULL,
                           cstatistic      = NULL,
                           tolerance       = 0.001,
                           n_bisect_pop    = 1e6,
                           n_synth         = 1e6,
                           max_iter        = 100,
                           seed            = NULL) {

  bisection_method <- match.arg(bisection_method)
  call <- match.call()

  # ---- 1. Resolve joint data --------------------------------------------------
  if (is.data.frame(joint_data)) {
    if (is.null(predictors)) predictors <- names(joint_data)
    missing_cols <- setdiff(predictors, names(joint_data))
    if (length(missing_cols) > 0) {
      rlang::abort(paste0("Columns not found in joint_data: ",
                          paste(missing_cols, collapse = ", ")))
    }
    pop_data <- joint_data[, predictors, drop = FALSE]

    if (bisection && bisection_method == "independent") {
      # For bisection, fit independent marginal distributions from the data
      # and generate a large synthetic population. This avoids degenerate AUC
      # estimates when pop_data is small, and keeps bisection well-conditioned.
      bisect_spec <- .fit_marginals(pop_data)
      bisect_data <- generate_synth_data(bisect_spec, n = n_bisect_pop, seed = seed)
    }
    # bisection_method == "mvn": the synthetic population is generated later
    # (section 2b), directly from pop_data's estimated correlation structure.

  } else if (is.list(joint_data)) {
    # Distributional assumptions
    if (bisection_method == "mvn") {
      rlang::abort("bisection_method = 'mvn' requires joint_data to be a data frame (predictors from a distributional-assumptions list are already independent by construction; use bisection_method = 'independent').")
    }
    predictors <- names(joint_data)
    if (is.null(predictors) || any(predictors == "")) {
      rlang::abort("When joint_data is a list, all elements must be named.")
    }
    pop_data <- generate_synth_data(joint_data, n = n_synth, seed = seed)
    if (bisection) bisect_data <- pop_data   # same population serves both roles

  } else {
    rlang::abort("joint_data must be a data frame or a named list of distributional assumptions.")
  }

  X_pred <- as.matrix(pop_data)

  if (!bisection) {
    # ---- Bypass bisection: use the supplied reference model directly --------
    if (is.null(intercept) || is.null(coef)) {
      rlang::abort("'intercept' and 'coef' must both be supplied when bisection = FALSE.")
    }
    if (!setequal(names(coef), predictors)) {
      rlang::abort("Names of 'coef' must exactly match 'predictors' when bisection = FALSE.")
    }
    coef_final <- coef[predictors]
    b0_final   <- intercept

    lp_pop         <- b0_final + as.vector(X_pred %*% coef_final)
    p_pop          <- plogis(lp_pop)
    prev_achieved  <- mean(p_pop)
    y_pop          <- rbinom(length(p_pop), 1, p_pop)
    cstat_achieved <- .fast_auc(p_pop, y_pop)

    msg <- sprintf(
      "Using supplied reference model (bisection bypassed): prevalence=%.4f, c-stat=%.4f",
      prev_achieved, cstat_achieved
    )
    if (!is.null(prevalence)) {
      msg <- paste0(msg, sprintf(" (target prevalence=%.4f)", prevalence))
    }
    if (!is.null(cstatistic)) {
      msg <- paste0(msg, sprintf(" (target c-stat=%.4f)", cstatistic))
    }
    rlang::inform(msg)

  } else {
    # ---- 2. Resolve initial relative coefficients ----------------------------
    if (is.null(coef)) {
      coef_rel <- setNames(rep(1, length(predictors)), predictors)
    } else {
      if (!all(names(coef) %in% predictors)) {
        rlang::abort("Names of 'coef' must match 'predictors'.")
      }
      coef_rel <- coef[predictors]
    }

    # ---- 3. Validate inputs ----------------------------------------------------
    if (is.null(prevalence) || is.null(cstatistic)) {
      rlang::abort("'prevalence' and 'cstatistic' are required when bisection = TRUE.")
    }
    if (prevalence <= 0 || prevalence >= 1) {
      rlang::abort("'prevalence' must be strictly between 0 and 1.")
    }
    if (cstatistic <= 0.5 || cstatistic >= 1) {
      rlang::abort("'cstatistic' must be strictly between 0.5 and 1.")
    }

    if (bisection_method == "independent") {
      # ---- 4. Build design matrices ---------------------------------------------
      # X_bisect: used for the bisection procedure (large, well-conditioned)
      # X_pred:   used for unit information matrix (the original supplied data)
      X_bisect <- as.matrix(bisect_data[, predictors, drop = FALSE])

      # lp_base_bisect[i] = X_bisect[i,] %*% coef_rel  (no scalar, no intercept)
      lp_base_bisect <- as.vector(X_bisect %*% coef_rel)
      n_bisect       <- nrow(X_bisect)

      # ---- 5. Inner bisection: find intercept for target prevalence ------------
      # Runs on the bisection population. Given scalar s, find b0 such that
      # mean(plogis(b0 + s * lp_base_bisect)) = prevalence.
      find_intercept <- function(s) {
        lp_scaled <- s * lp_base_bisect
        b0_low  <- -50
        b0_high <-  50
        for (i in seq_len(max_iter)) {
          b0_mid   <- (b0_low + b0_high) / 2
          prev_emp <- mean(plogis(b0_mid + lp_scaled))
          if (abs(prev_emp - prevalence) < tolerance / 10) break
          if (prev_emp < prevalence) b0_low <- b0_mid else b0_high <- b0_mid
        }
        b0_mid
      }

      # ---- 6. Outer bisection: find scalar for target c-statistic --------------
      # Following Austin, cap scalar_high at 10. C-statistic is monotone in s so
      # bisection works directly.

      rlang::inform("Running bisection to calibrate reference model...")

      scalar_low  <- 0
      scalar_high <- 10
      cstat_emp   <- 0

      # Verify that scalar_high gives c-stat above the target.
      b0_check <- find_intercept(scalar_high)
      lp_check <- b0_check + scalar_high * lp_base_bisect
      p_check  <- plogis(lp_check)
      y_check  <- rbinom(n_bisect, 1, p_check)
      cs_check <- .fast_auc(p_check, y_check)
      if (is.na(cs_check) || cs_check < cstatistic) {
        rlang::abort(paste0(
          "Cannot reach target c-statistic of ", cstatistic,
          " even at scalar=10 (achieved ",
          if (is.na(cs_check)) "NA" else round(cs_check, 3), "). ",
          "Check predictor effect sizes or try a lower target."
        ))
      }

      b0_final     <- NA_real_
      scalar_final <- NA_real_

      for (iter in seq_len(max_iter)) {
        scalar_mid <- (scalar_low + scalar_high) / 2
        b0_mid     <- find_intercept(scalar_mid)
        lp_mid     <- b0_mid + scalar_mid * lp_base_bisect
        p_mid      <- plogis(lp_mid)
        y_mid      <- rbinom(n_bisect, 1, p_mid)
        cstat_emp  <- .fast_auc(p_mid, y_mid)

        if (!is.na(cstat_emp) && abs(cstat_emp - cstatistic) < tolerance) {
          b0_final     <- b0_mid
          scalar_final <- scalar_mid
          break
        }
        if (is.na(cstat_emp) || cstat_emp < cstatistic) {
          scalar_low <- scalar_mid
        } else {
          scalar_high <- scalar_mid
        }

        if (iter == max_iter) {
          rlang::warn(paste0(
            "Bisection reached max_iter=", max_iter,
            " without converging. Final c-stat: ", round(cstat_emp, 4),
            ". Consider increasing max_iter or widening tolerance."
          ))
          b0_final     <- b0_mid
          scalar_final <- scalar_mid
        }
      }

      # Final scaled coefficients
      coef_final <- scalar_final * coef_rel

      # Final achieved statistics (evaluated on the bisection population)
      lp_final      <- b0_final + as.vector(X_bisect %*% coef_final)
      p_final       <- plogis(lp_final)
      prev_achieved <- mean(p_final)
      cstat_achieved <- cstat_emp

      rlang::inform(sprintf(
        "Bisection converged: prevalence=%.4f (target=%.4f), c-stat=%.4f (target=%.4f)",
        prev_achieved, prevalence, cstat_achieved, cstatistic
      ))

    } else {
      # ---- "mvn" method: correlation-preserving analytic calibration -----------
      rlang::inform("Calibrating reference model via multivariate-normal approximation...")

      mvn_synth <- generate_mvn_synth_data(pop_data, n = n_bisect_pop, seed = seed)
      X_bisect  <- as.matrix(mvn_synth$data[, predictors, drop = FALSE])

      mu_sigma      <- .find_mu_sigma(prevalence, cstatistic)
      b0_final      <- unname(mu_sigma["mu"])
      target_lp_var <- unname(mu_sigma["variance"])

      raw_lp_var  <- as.numeric(t(coef_rel) %*% mvn_synth$sigma_x %*% coef_rel)
      coef_final  <- coef_rel * sqrt(target_lp_var / raw_lp_var)

      lp_final       <- b0_final + as.vector(X_bisect %*% coef_final)
      p_final        <- plogis(lp_final)
      prev_achieved  <- mean(p_final)
      y_final        <- rbinom(length(p_final), 1, p_final)
      cstat_achieved <- .fast_auc(p_final, y_final)

      rlang::inform(sprintf(
        "MVN calibration complete: prevalence=%.4f (target=%.4f), c-stat=%.4f (target=%.4f)",
        prev_achieved, prevalence, cstat_achieved, cstatistic
      ))
    }
  }

  # ---- 7. Unit information matrix (computed on the original pop_data) ----------
  # Design matrix includes intercept
  X_full  <- cbind(1, X_pred)
  lp_ref  <- b0_final + as.vector(X_pred %*% coef_final)

  unit_info  <- compute_unit_info_matrix(X_full, lp_ref)
  inv_unit_info <- tryCatch(
    solve(unit_info),
    error = function(e) {
      rlang::warn("Unit information matrix is singular; using pseudoinverse.")
      MASS::ginv(unit_info)
    }
  )

  rlang::inform("Unit information matrix computed and cached.")

  # ---- 8. Return object -------------------------------------------------------
  new_pmgen_ref_model(
    coef                = coef_final,
    intercept           = b0_final,
    prevalence_achieved = prev_achieved,
    cstat_achieved      = cstat_achieved,
    predictors          = predictors,
    joint_data          = pop_data,
    unit_info_matrix    = unit_info,
    inv_unit_info       = inv_unit_info,
    call                = call
  )
}
